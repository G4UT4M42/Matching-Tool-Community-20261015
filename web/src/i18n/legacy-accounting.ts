/** Known report-generated warnings are localized without changing identifiers or original stored evidence. */
export function accountingWarningText(text: AccountingText, value: string): string {
  let match = /^(.*): kein Dateiname vorhanden$/.exec(value);
  if (match) return match[1] + ': ' + text('Kein Dateiname vorhanden');
  const prefix = (label: string) => label.replace(/^Income /, text('Einnahme') + ' ').replace(/^Expense /, text('Ausgabe') + ' ');
  match = /^(Income .*): kein Land angegeben, nicht klassifizierbar$/.exec(value);
  if (match) return prefix(match[1]) + ': ' + text('Kein Land angegeben, nicht klassifizierbar');
  match = /^(Income .*|Expense .*): AT aber Steuersatz (.*) \(nicht 20%\)$/.exec(value);
  if (match) return prefix(match[1]) + ': ' + text('AT aber Steuersatz {rate} (nicht 20%)', { rate: match[2] === 'fehlt' ? text('fehlt') : match[2] });
  match = /^(Expense .*): AT VAT rate missing; no input VAT deduction without original evidence$/.exec(value);
  if (match) return prefix(match[1]) + ': ' + text('AT-Steuersatz fehlt; ohne Originalbeleg kein Vorsteuerabzug');
  return value;
}
